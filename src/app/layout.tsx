import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Script from "next/script";
import "./globals.css";
import { ThemeProvider } from "@/providers/ThemeProvider";
import { QueryProvider } from "@/providers/QueryProvider";
import { I18nProvider } from '@/providers/I18nProvider';
import { cookies, headers } from 'next/headers';

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const cookieStore = await cookies();
  const cookieLocale = cookieStore.get('NEXT_LOCALE')?.value;
  const hdrs = await headers();
  const accept = hdrs.get('accept-language') || '';
  const fallback = 'en';
  const headerLocale = accept.split(',')[0]?.slice(0, 2);
  const locale = (cookieLocale === 'ko' || cookieLocale === 'en')
    ? cookieLocale
    : (headerLocale === 'ko' ? 'ko' : fallback);
  const messages = (await import(`@/messages/${locale}.json`)).default;
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <Script id="theme-init" strategy="beforeInteractive">
          {`
            try {
              var t = localStorage.getItem('theme');
              document.documentElement.setAttribute('data-theme', (t === 'dark' || t === 'light') ? t : 'light');
            } catch { document.documentElement.setAttribute('data-theme', 'light'); }
          `}
        </Script>
      </head>
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
        <ThemeProvider>
          <I18nProvider messages={messages} locale={locale}>
            <QueryProvider>{children}</QueryProvider>
          </I18nProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
